#!/usr/bin/env python3
"""
Summarize Clang -ftime-trace profiles across build directories.

Scans the build directory for .json trace files generated by Clang's -ftime-trace flag
and aggregates:
1. Slowest Translation Units
2. Most expensive header files (cumulative parse time)
3. Heaviest template instantiations
"""

import json
import os
import sys
from collections import defaultdict
from pathlib import Path


def format_duration(microseconds: float) -> str:
    seconds = microseconds / 1_000_000.0
    if seconds >= 1.0:
        return f"{seconds:6.2f}s"
    milliseconds = microseconds / 1_000.0
    return f"{milliseconds:6.1f}ms"


def analyze_traces(build_dir: Path) -> None:
    if not build_dir.exists():
        print(f"Error: Build directory not found: {build_dir}", file=sys.stderr)
        sys.exit(1)

    trace_files = []
    for root, _, files in os.walk(build_dir):
        for f in files:
            if f.endswith(".json") and f != "compile_commands.json" and not f.startswith("baseline"):
                full_path = Path(root) / f
                trace_files.append(full_path)

    if not trace_files:
        print(f"No Clang -ftime-trace JSON files found in {build_dir}.")
        print("Ensure the project was built with -DENABLE_TIME_TRACE=ON using Clang.")
        return

    tu_times = []  # (duration_us, tu_name, frontend_us, backend_us)
    header_times = defaultdict(float)  # header_path -> cumulative_us
    header_counts = defaultdict(int)   # header_path -> count_of_tus
    template_times = defaultdict(float)  # template_name -> cumulative_us

    for trace_path in trace_files:
        try:
            with open(trace_path, "r", encoding="utf-8", errors="replace") as f:
                data = json.load(f)
        except Exception:
            continue

        events = data.get("traceEvents", [])
        if not events:
            continue

        total_us = 0.0
        frontend_us = 0.0
        backend_us = 0.0
        headers_seen_in_tu = set()
        pending_sources = {}  # id -> (ts, detail)

        for ev in events:
            name = ev.get("name", "")
            ph = ev.get("ph", "")
            ts = float(ev.get("ts", 0))
            dur = float(ev.get("dur", 0))
            args = ev.get("args", {})
            detail = args.get("detail", "")
            ev_id = ev.get("id")

            if name == "ExecuteCompiler":
                total_us = max(total_us, dur)
            elif name == "Frontend":
                frontend_us += dur
            elif name == "Backend":
                backend_us += dur
            elif name == "Source":
                if ph == "X":
                    header_times[detail] += dur
                    headers_seen_in_tu.add(detail)
                elif ph == "b" and ev_id is not None:
                    pending_sources[ev_id] = (ts, detail)
                elif ph == "e" and ev_id is not None and ev_id in pending_sources:
                    start_ts, h_detail = pending_sources.pop(ev_id)
                    h_dur = max(0.0, ts - start_ts)
                    header_times[h_detail] += h_dur
                    headers_seen_in_tu.add(h_detail)
            elif (name == "InstantiateFunction" or name == "InstantiateClass") and detail:
                template_times[detail] += dur

        for h in headers_seen_in_tu:
            header_counts[h] += 1

        tu_name = trace_path.stem
        if tu_name.endswith(".cpp") or tu_name.endswith(".mm"):
            tu_name = tu_name  # keep filename
        tu_times.append((total_us if total_us > 0 else (frontend_us + backend_us), tu_name, frontend_us, backend_us))

    tu_times.sort(key=lambda x: x[0], reverse=True)

    print("\n" + "=" * 80)
    print(" Clang Build Time Trace Summary (-ftime-trace)")
    print("=" * 80)
    print(f"Total analyzed translation units: {len(tu_times)}\n")

    print("--- Top 15 Slowest Translation Units ---")
    print(f"{'Time':>10} | {'Frontend':>10} | {'Backend':>10} | Translation Unit")
    print("-" * 80)
    for total_us, name, f_us, b_us in tu_times[:15]:
        print(f"{format_duration(total_us):>10} | {format_duration(f_us):>10} | {format_duration(b_us):>10} | {name}")

    sorted_headers = sorted(header_times.items(), key=lambda x: x[1], reverse=True)
    print("\n--- Top 15 Most Expensive Headers (Cumulative Parse Time) ---")
    print(f"{'Total Time':>10} | {'TUs':>5} | Header File")
    print("-" * 80)
    for h_path, h_us in sorted_headers[:15]:
        print(f"{format_duration(h_us):>10} | {header_counts[h_path]:>5} | {h_path}")

    sorted_templates = sorted(template_times.items(), key=lambda x: x[1], reverse=True)
    if sorted_templates:
        print("\n--- Top 10 Most Expensive Template Instantiations ---")
        print(f"{'Total Time':>10} | Template Detail")
        print("-" * 80)
        for t_name, t_us in sorted_templates[:10]:
            print(f"{format_duration(t_us):>10} | {t_name}")

    print("\n" + "=" * 80)
    print("Tip: Drop any individual *.json trace file into https://ui.perfetto.dev")
    print("     or chrome://tracing to view a detailed interactive flamegraph.")
    print("=" * 80 + "\n")


def main() -> None:
    target_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("build")
    analyze_traces(target_dir)


if __name__ == "__main__":
    main()
